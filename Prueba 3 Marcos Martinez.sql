-- Creación de tablas
CREATE TABLE Usuario (
    usu_id NUMBER PRIMARY KEY,
    usu_nombre VARCHAR2(100),
    usu_rol VARCHAR2(20),
    usu_contrasena VARCHAR2(200)
);

CREATE TABLE Producto (
    pro_id NUMBER PRIMARY KEY,
    pro_nombre VARCHAR2(100),
    pro_precio NUMBER,
    pro_stock NUMBER
);

CREATE TABLE Boleta (
    bol_id NUMBER PRIMARY KEY,
    bol_fecha DATE DEFAULT SYSDATE,
    usu_id NUMBER,
    FOREIGN KEY (usu_id) REFERENCES Usuario(usu_id)
);

CREATE TABLE BoletaProducto (
    bolPro_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bolPro_bol_id NUMBER NOT NULL,
    bolPro_pro_id NUMBER NOT NULL,
    bolPro_cantidad NUMBER NOT NULL,
    FOREIGN KEY (bolPro_bol_id) REFERENCES Boleta(bol_id),
    FOREIGN KEY (bolPro_pro_id) REFERENCES Producto(pro_id)
);

