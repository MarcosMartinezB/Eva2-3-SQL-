CREATE OR REPLACE PROCEDURE disminuirStock(
    p_id IN NUMBER,
    p_cantidad IN NUMBER
) IS
    v_stock NUMBER;
BEGIN
    IF p_cantidad <= 0 THEN
        RAISE_APPLICATION_ERROR(-20014, 'Cantidad a disminuir debe ser positiva.');
    END IF;
    SELECT pro_stock INTO v_stock 
    FROM Producto 
    WHERE pro_id = p_id 
    FOR UPDATE;
    IF v_stock < p_cantidad THEN
        RAISE_APPLICATION_ERROR(-20015, 'Stock insuficiente.');
    END IF;
     UPDATE Producto 
    SET pro_stock = pro_stock - p_cantidad 
    WHERE pro_id = p_id;
    DBMS_OUTPUT.PUT_LINE('Stock disminuido en ' || p_cantidad || ' para producto ID ' || p_id);
END disminuirStock;
/
--Valida que el ID exista
EXEC disminuirStock(4,200);
-- Valida que el stock sea suficiente
SELECT * from producto;
EXEC disminuirStock(1,901);

-- Eliminar productos siempre y cundo no esten vinculado a una boleta
CREATE OR REPLACE PROCEDURE eliminarProducto(p_id IN NUMBER) IS
v_count NUMBER;
BEGIN
SELECT COUNT(*) INTO v_count FROM BoletaProducto WHERE bolPro_pro_id = p_id;
IF v_count > 0 THEN
RAISE_APPLICATION_ERROR(-20020, 'No se puede eliminar producto vinculado a boleta.');
END IF;
DELETE FROM Producto WHERE pro_id = p_id;
DBMS_OUTPUT.PUT_LINE('Producto eliminado ID ' || p_id);
END eliminarProducto;
/

