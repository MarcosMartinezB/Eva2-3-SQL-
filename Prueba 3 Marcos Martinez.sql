-- Procedimiento Modificar STOCK

CREATE OR REPLACE PROCEDURE modificarStock(
    p_id IN NUMBER,
    p_nuevo_stock IN NUMBER
) IS
    v_count NUMBER;
BEGIN
    IF p_nuevo_stock < 0 THEN
        RAISE_APPLICATION_ERROR(-20010, 'Stock nuevo no puede ser negativo');
    END IF;
    SELECT COUNT(*) INTO v_count FROM Producto WHERE pro_id = p_id;
    IF v_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20011, 'Producto no existe');
    END IF;
    UPDATE Producto SET pro_stock = p_nuevo_stock WHERE pro_id = p_id;
    DBMS_OUTPUT.PUT_LINE('Stock modificado para producto ID ' || p_id || ' a ' || p_nuevo_stock);
END modificarStock;
/
-- Valida que el stock actualizado no sea negativo
EXEC modificarStock (1,-200);

CREATE OR REPLACE PROCEDURE aumentarStock(
    p_id IN NUMBER,
    p_cantidad IN NUMBER
) IS
    v_count NUMBER;
BEGIN
    IF p_cantidad <= 0 THEN
        RAISE_APPLICATION_ERROR(-20012, 'Cantidad a aumentar debe ser positiva.');
    END IF;
    SELECT COUNT(*) INTO v_count FROM Producto WHERE pro_id = p_id;
    IF v_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20013, 'Producto no existe.');
    END IF;
    UPDATE Producto SET pro_stock = pro_stock + p_cantidad WHERE pro_id = p_id;
    DBMS_OUTPUT.PUT_LINE('Stock aumentado en ' || p_cantidad || ' para producto ID ' || p_id);
END aumentarStock;
/
