--Ver boleta usando procedimiento  (NO PIDE VERIFICIÓN POR EXISTENCIA DE BOLETA ID )
CREATE OR REPLACE PROCEDURE verBoletaCompleta(p_bol_id IN NUMBER) IS
    v_total NUMBER := 0;
    BEGIN
        FOR r IN (
            SELECT bp.bolPro_cantidad, pr.pro_nombre, pr.pro_precio, (bp.bolPro_cantidad * pr.pro_precio) AS subtotal
        FROM BoletaProducto bp
        JOIN Producto pr ON bp.bolPro_pro_id = pr.pro_id
        WHERE bp.bolPro_bol_id = p_bol_id
                    ) LOOP
        DBMS_OUTPUT.PUT_LINE(r.pro_nombre || ' - Cant: '|| r.bolPro_cantidad || ' - Precio: '|| r.pro_precio || ' - Subtotal: ' || r.subtotal);
        v_total := v_total + r.subtotal;
                    END LOOP;   
        DBMS_OUTPUT.PUT_LINE('TOTAL BOLETA ('||p_bol_id||'): '|| v_total);
END verBoletaCompleta;
/

EXEC verBoletaCompleta(11);

