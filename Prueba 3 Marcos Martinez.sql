CREATE OR REPLACE PROCEDURE registrarUsuario(
    u_id IN NUMBER,
    u_nombre IN VARCHAR2,
    u_rol IN VARCHAR2,
    u_contra IN VARCHAR2
) AS
    u_contra_raw RAW(2000);
    u_contra_hash RAW(2000);
    contador_de_usu NUMBER;
BEGIN 
    SELECT COUNT(*) INTO contador_de_usu FROM usuario WHERE usu_id = u_id;
    
    IF contador_de_usu > 0 THEN
        RAISE_APPLICATION_ERROR(-20010, 'ID del usuario ya existe');
        END IF;
    IF LENGTH(u_contra) < 6 THEN
        RAISE_APPLICATION_ERROR(-20050, 'La contraseña debe tener al menos 6 caracteres');
        END IF;
    
    u_contra_raw := UTL_I18N.STRING_TO_RAW(u_contra, 'AL32UTF8');
    u_contra_hash := UTL_RAW.CAST_TO_RAW(u_contra_raw);
    
    INSERT INTO usuario VALUES(u_id, u_nombre, u_rol, RAWTOHEX(u_contra_hash));
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Usuario registrado correctamente');
    END registrarUsuario;
/
--Probando la Encriptación 
EXEC registrarUsuario(1,'Marcos Martínez','Estudiante','Valtiel');
-- Valida que contraseña sea mayor a 6 digitos
EXEC registrarUsuario(3,'Error contra chica','Administrador','con4');

CREATE OR REPLACE PROCEDURE validarUsuarioContrasena(
    nom_u IN VARCHAR2, 
    contra_u IN VARCHAR2) 
AS
    u_encontrado NUMBER;
    u_contra_raw RAW(2000);
    u_contra_hash RAW(2000);
    u_contra_hashBD VARCHAR2(200);
BEGIN
    SELECT COUNT(*) INTO u_encontrado FROM usuario WHERE usu_nombre = nom_u;
    
    IF u_encontrado = 0 THEN
        RAISE_APPLICATION_ERROR(-20010, 'Solicitud denegada');
    END IF;
    
    u_contra_raw := UTL_I18N.STRING_TO_RAW(contra_u, 'AL32UTF8');
    u_contra_hash := UTL_RAW.CAST_TO_RAW(u_contra_raw);
    
    SELECT usu_contrasena INTO u_contra_hashBD FROM usuario WHERE usu_nombre = nom_u;
    
    IF u_contra_hashBD = RAWTOHEX(u_contra_hash) THEN
        DBMS_OUTPUT.PUT_LINE('Inicio de Sesión valido');
    ELSE
        DBMS_OUTPUT.PUT_LINE('Credenciales incorrectas');
    END IF;
    
END validarUsuarioContrasena; 
/

