CREATE OR REPLACE PROCEDURE registrarProducto(
    p_id IN NUMBER,
    p_nombre IN VARCHAR2,
    p_precio IN NUMBER,
    p_stock IN NUMBER
) IS
    v_exists NUMBER;
BEGIN
    IF p_precio <= 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Precio debe ser mayor que 0');
    END IF;
    IF p_stock < 0 THEN
        RAISE_APPLICATION_ERROR(-20002, 'Stock no puede ser negativo');
    END IF;
    SELECT COUNT(*) INTO v_exists FROM Producto WHERE pro_nombre = p_nombre;
    IF v_exists > 0 THEN
        RAISE_APPLICATION_ERROR(-20003, 'Nombre de producto ya existe');
    END IF;
    INSERT INTO Producto(pro_id, pro_nombre, pro_precio, pro_stock)
    VALUES(p_id, p_nombre, p_precio, p_stock);
    DBMS_OUTPUT.PUT_LINE('Producto registrado: ' || p_nombre);
END registrarProducto;
/
